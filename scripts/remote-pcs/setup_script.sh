#!/bin/bash
set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Refuse to provision the live ISO session. The live image boots with
# boot=casper; changes made here are thrown away, and the work (apt installs,
# initramfs rebuilds) delays the display manager so long that boot appears to
# hang on a black screen. The installed system does not have boot=casper, so
# this guard only affects the live environment.
if grep -qw 'boot=casper' /proc/cmdline 2>/dev/null; then
    echo "Live ISO environment detected (boot=casper); skipping JMX setup."
    exit 0
fi

echo ">>> [1] Load custom branding..."
source branding/branding.sh

echo ">>> [2] Installing system dependencies..."
sudo apt update
sudo apt install -y build-essential python3 openjdk-21-jdk openbox firejail sqlite3 libsqlite3-dev ca-certificates curl gnupg \
  xdotool wmctrl x11-xserver-utils picom

echo ">>> [2.1] Writing JMX daemon configuration..."
sudo install -d -m 0755 /etc/jmxd

write_jmx_config=0
if [ ! -f /etc/jmxd/jmxd.conf ] || [ "${JMX_FORCE_CONFIG:-0}" = "1" ]; then
  write_jmx_config=1
fi

if [ "$write_jmx_config" = "1" ]; then
  if [ -f /etc/jmxd/jmxd.conf ]; then
    backup="/etc/jmxd/jmxd.conf.bak.$(date +%s)"
    sudo cp -a /etc/jmxd/jmxd.conf "$backup"
    echo "Backed up existing config to $backup"
  fi

  JMX_SERVER_ADDRESS="${JMX_SERVER_ADDRESS:-127.0.0.1}"
  JMX_SERVER_PORT="${JMX_SERVER_PORT:-8080}"
  JMX_SESSION_DURATION_HOURS="${JMX_SESSION_DURATION_HOURS:-2}"

  sudo tee /etc/jmxd/jmxd.conf >/dev/null <<EOF
# Generated by scripts/remote-pcs/setup_script.sh
socket_directory = /run/jmx
workspace_directory = /home/examkiosk/exam_workspace
server_address = ${JMX_SERVER_ADDRESS}
server_port = ${JMX_SERVER_PORT}
session_duration_in_hours = ${JMX_SESSION_DURATION_HOURS}
EOF
  sudo chmod 0644 /etc/jmxd/jmxd.conf
else
  echo "Existing /etc/jmxd/jmxd.conf preserved (set JMX_FORCE_CONFIG=1 to rewrite)."
fi

echo ">>> [2.2] Configuring JMX APT repository..."
JMX_APT_URL="${JMX_APT_URL:-https://yetanothernaveed.github.io/JMX-APT}"
JMX_APT_URL="${JMX_APT_URL%/}"

sudo install -d -m 0755 /etc/apt/keyrings
curl -fsSL --retry 5 --retry-delay 5 \
  "$JMX_APT_URL/KEY.gpg" |
  sudo gpg --dearmor --yes -o /etc/apt/keyrings/jmx.gpg

echo "deb [signed-by=/etc/apt/keyrings/jmx.gpg] $JMX_APT_URL stable main" |
  sudo tee /etc/apt/sources.list.d/jmx.list >/dev/null

sudo apt-get update
sudo apt-get install -y jmxremote

echo ">>> [3] Installing VS Code..."
sudo apt-get install -y wget gpg
wget -qO- https://packages.microsoft.com/keys/microsoft.asc | gpg --dearmor > packages.microsoft.gpg
sudo install -D -o root -g root -m 644 packages.microsoft.gpg /etc/apt/keyrings/packages.microsoft.gpg
sudo sh -c 'echo "deb [arch=amd64,arm64,armhf signed-by=/etc/apt/keyrings/packages.microsoft.gpg] https://packages.microsoft.com/repos/code stable main" > /etc/apt/sources.list.d/vscode.list'
rm -f packages.microsoft.gpg
sudo apt update && sudo apt install -y code

echo ">>> [4] Creating examkiosk user and workspace..."
if ! id examkiosk &>/dev/null; then
    adduser --disabled-password --gecos "" examkiosk
fi

EXAMKIOSK_PASSWORD="2304"
echo "examkiosk:${EXAMKIOSK_PASSWORD}" | chpasswd

mkdir -p /home/examkiosk/exam_workspace
chown examkiosk:examkiosk /home/examkiosk/exam_workspace
chmod 700 /home/examkiosk/exam_workspace

echo ">>> [5] Creating new user group jmx and adding user examkiosk to the jmx group"
getent group jmx >/dev/null || groupadd --system jmx
sudo usermod -aG jmx examkiosk

# jmxd may have started during package installation before the workspace and
# group existed. Restart it so systemd applies the ReadWritePaths entry.
sudo systemctl restart jmxd.service || true

echo ">>> [6] Setting up VS Code config directories and installing extensions..."
if [ -f /home/examkiosk/.config/Code/User/settings.json ]; then
    sudo chattr -i /home/examkiosk/.config/Code/User/settings.json
